
-- =====================================================
-- 智能问答知识库
-- =====================================================
DROP TABLE IF EXISTS `knowledge_base`;
CREATE TABLE `knowledge_base` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `category` VARCHAR(20) NOT NULL DEFAULT 'general' COMMENT '分类: frontend/backend/database/general',
    `question` VARCHAR(500) NOT NULL COMMENT '问题',
    `answer` TEXT NOT NULL COMMENT '答案',
    `keywords` VARCHAR(500) DEFAULT NULL COMMENT '关键词，逗号分隔',
    `synonyms` VARCHAR(1000) DEFAULT NULL COMMENT '同义词扩展，格式: 词1=同义词1,同义词2|词2=同义词A,同义词B',
    `sort_order` INT NOT NULL DEFAULT 0 COMMENT '排序',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`id`),
    INDEX `idx_category` (`category`),
    INDEX `idx_sort` (`sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='智能问答知识库';

-- =====================================================
-- 未命中问题日志
-- =====================================================
DROP TABLE IF EXISTS `unanswered_log`;
CREATE TABLE `unanswered_log` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `question` VARCHAR(500) NOT NULL COMMENT '用户问题',
    `category` VARCHAR(20) DEFAULT NULL COMMENT '分类',
    `answered` TINYINT NOT NULL DEFAULT 0 COMMENT '0未补充 1已补充',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`id`),
    INDEX `idx_answered` (`answered`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='未命中问题日志';


